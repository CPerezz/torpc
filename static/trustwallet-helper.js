// Trust Wallet Helper - WalletConnect Integration for ToRPC Proxy

const TrustWalletHelper = {
    // WalletConnect configuration
    walletConnectConfig: {
        bridge: "https://bridge.walletconnect.org",
        qrcodeModal: null, // Will be set if QRCode modal is available
    },

    // Query the proxy discovery API (same as MetaMask)
    async queryProxyDiscovery() {
        const discoveryUrl = 'http://localhost:8081/api/discovery';
        
        try {
            const controller = new AbortController();
            const timeoutId = setTimeout(() => controller.abort(), 2000);
            
            const response = await fetch(discoveryUrl, {
                method: 'GET',
                mode: 'cors',
                headers: {
                    'Accept': 'application/json',
                },
                signal: controller.signal
            });
            
            clearTimeout(timeoutId);
            
            if (!response.ok) {
                throw new Error(`HTTP error! status: ${response.status}`);
            }
            
            const data = await response.json();
            
            return {
                success: true,
                data: data,
                rpcUrl: data.suggested_rpc_url || `http://${data.proxy.listen_addr}`
            };
        } catch (error) {
            if (error.name === 'AbortError' || error.message.includes('Failed to fetch')) {
                return {
                    success: false,
                    error: 'ToRPC proxy not detected',
                    message: 'Please ensure the ToRPC proxy client is running.',
                    fallbackUrl: 'http://localhost:9000'
                };
            }
            
            return {
                success: false,
                error: error.message,
                fallbackUrl: 'http://localhost:9000'
            };
        }
    },


    // Generate Trust Wallet deep link
    generateDeepLink(rpcUrl, chainId = '1') {
        // Trust Wallet deep link format for adding custom network
        const networkName = 'ToRPC Privacy Network';
        const symbol = 'ETH';
        
        // Encode parameters
        const params = new URLSearchParams({
            network: networkName,
            rpcUrl: rpcUrl,
            chainId: chainId,
            symbol: symbol
        });

        // Trust Wallet universal link
        return `https://link.trustwallet.com/add_network?${params.toString()}`;
    },

    // Generate WalletConnect URI for Trust Wallet
    generateWalletConnectURI(rpcUrl, chainId = '1') {
        // This would typically be generated by WalletConnect SDK
        // For now, we'll create a manual configuration URI
        const config = {
            name: 'ToRPC Privacy Network',
            rpcUrl: rpcUrl,
            chainId: parseInt(chainId),
            nativeCurrency: {
                name: 'Ethereum',
                symbol: 'ETH',
                decimals: 18
            }
        };

        return JSON.stringify(config);
    },

    // Copy text to clipboard
    async copyToClipboard(text) {
        try {
            await navigator.clipboard.writeText(text);
            return true;
        } catch (error) {
            // Fallback for older browsers
            const textArea = document.createElement('textarea');
            textArea.value = text;
            textArea.style.position = 'fixed';
            textArea.style.left = '-999999px';
            document.body.appendChild(textArea);
            textArea.select();
            const success = document.execCommand('copy');
            document.body.removeChild(textArea);
            return success;
        }
    },

    // Check if Trust Wallet is available (mobile browser)
    isTrustWalletBrowser() {
        return typeof window.ethereum !== 'undefined' && 
               window.ethereum.isTrust === true;
    },

    // Check if on mobile device
    isMobileDevice() {
        return /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(navigator.userAgent);
    },

    // Open Trust Wallet app with deep link
    openTrustWallet(deepLink) {
        if (this.isMobileDevice()) {
            // On mobile, try to open the app
            window.location.href = deepLink;
        } else {
            // On desktop, open in new tab
            window.open(deepLink, '_blank');
        }
    }
};

// Export for use in other scripts
window.TrustWalletHelper = TrustWalletHelper;